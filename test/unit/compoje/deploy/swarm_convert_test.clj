(ns unit.compoje.deploy.swarm-convert-test
  "The reference stack test-resources/swarm/ref-stack/stack.yml covers every
   supported key. Its expected plan was generated by compoje and checked
   against `docker stack deploy`: the services, networks, secret and config
   that both engines create are identical (docker 29, API 1.47). Regenerate
   with `regenerate!` below after intended changes, and re-check with docker."
  (:require [babashka.fs :as fs]
            [cheshire.core :as json]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [compoje.deploy.swarm-convert :as c]))

(def ref-dir "test-resources/swarm/ref-stack")

(defn- plan [text & [opts]]
  (c/convert (c/parse-stack text)
             (merge {:stack "ref" :template-dir "/stack"
                     :read-file #(slurp (str (fs/path ref-dir %)))
                     :getenv {}}
                    opts)))

(defn- as-json [x] (json/parse-string (json/generate-string x)))

(defn regenerate! []
  (spit (str (fs/path ref-dir "expected-plan.json"))
        (json/generate-string (plan (slurp (str (fs/path ref-dir "stack.yml")))) {:pretty true})))

(deftest reference-stack
  (is (= (json/parse-string (slurp (str (fs/path ref-dir "expected-plan.json"))))
         (as-json (plan (slurp (str (fs/path ref-dir "stack.yml"))))))))

(deftest yaml-1-1-octal-modes
  (let [p (plan "services:\n  a:\n    image: i\n    secrets:\n      - source: s\n        mode: 0400\nsecrets:\n  s:\n    file: x\n")]
    (is (= 256 (-> p :services first :secret-refs first :mode)))))

(deftest default-network-only-when-used
  (is (= ["ref_n"] (map :name (:networks (plan "services:\n  a:\n    image: i\n    networks: [n]\nnetworks:\n  n: {}\n")))))
  (is (= ["ref_default"] (map :name (:networks (plan "services:\n  a:\n    image: i\n"))))))

(deftest unsupported-and-ignored
  (testing "unsupported keys are one error listing them all"
    (let [msg (try (plan "services:\n  a:\n    image: i\n    gpus: all\n    deploy:\n      foo: 1\ninclude: []\n") nil
                   (catch clojure.lang.ExceptionInfo e (ex-message e)))]
      (is (str/includes? msg "does not support"))
      (is (str/includes? msg "  include"))
      (is (str/includes? msg "  services.a.deploy.foo"))
      (is (str/includes? msg "  services.a.gpus"))))
  (testing "keys docker stack ignores are reported, not errors"
    (is (= [["services" "a" "build"] ["services" "a" "restart"]]
           (:ignored (plan "services:\n  a:\n    image: i\n    build: .\n    restart: always\n")))))
  (testing "x- extension keys are fine anywhere"
    (is (some? (plan "x-compoje: {}\nservices:\n  a:\n    image: i\n    x-note: hi\n")))))

(deftest undefined-references
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"undefined network n"
                        (plan "services:\n  a:\n    image: i\n    networks: [n]\n")))
  (is (thrown-with-msg? clojure.lang.ExceptionInfo #"undefined volume v"
                        (plan "services:\n  a:\n    image: i\n    volumes: [\"v:/d\"]\n"))))

(deftest empty-definitions
  (testing "`v:` / `n:` with no body (all defaults) are definitions, like {} (docker accepts them)"
    (let [p (plan (str "services:\n  a:\n    image: i\n    networks: [n]\n    volumes: [\"v:/d\"]\n"
                       "networks:\n  n:\nvolumes:\n  v:\n"))
          task (get-in (first (:services p)) [:spec "TaskTemplate"])]
      (is (= [{"Type" "volume" "Source" "ref_v" "Target" "/d"
               "VolumeOptions" {"Labels" {"com.docker.stack.namespace" "ref"}}}]
             (get-in task ["ContainerSpec" "Mounts"])))
      (is (= [{"Target" "ref_n" "Aliases" ["a"]}] (get task "Networks")))
      (is (= ["ref_n"] (map :name (:networks p)))))))

(deftest external-objects
  (let [p (plan (str "services:\n  a:\n    image: i\n    networks: [host_net]\n"
                     "networks:\n  host_net:\n    name: host\n    external: true\n"
                     "secrets:\n  s:\n    external: true\n    name: shared-s\n"))]
    (is (= [{"Target" "host" "Aliases" ["a"]}]
           (get-in (first (:services p)) [:spec "TaskTemplate" "Networks"])))
    (is (= {:key "s" :name "shared-s" :external true}
           (select-keys (first (:secrets p)) [:key :name :external])))))
